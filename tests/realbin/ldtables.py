#!/usr/bin/env python3
"""ldtables.py - the real MUTOS 1700 ld's initialized data, for the port.

The port of ld (src/mutos_ld/, "The port of ld" in
docs/devlog/originals_and_ports.md) runs on an image of the original's
64K data segment, so that every address the original computes - also
where it runs past an array (a long -l name written over the strings
after "/usr/lib/libxxxxxxxxxxxxxxx", a 257th archive member written past
liblist[]) - reads and writes what the original reads and writes. This
script writes that segment's initialized part, the binary's own bytes,
as C: lddata.c. Nothing in it is typed by hand. The binary is stripped;
tests/realbin/ldmap.txt names its functions and data.

Usage:
    ldtables.py --c                 print lddata.c
    ldtables.py --check-c FILE      check FILE is what --c prints
    ldtables.py --strings           print the strings of ld.o's data
"""
import base64
import os
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..', '..'))
BIN = os.path.join(ROOT, 'mutos', 'mutos_bin', 'ld.golden.base64.txt')

# ld.o's data: from crt0's words to the last string ("output error");
# libc.a's data begins at 02e0 ("(null)", then the stdio structures)
LD_DATA = (0x000a, 0x02e0)


def segments():
    img = base64.b64decode(open(BIN, 'rb').read())
    magic, tsize, dsize, bsize = struct.unpack_from('<4H', img, 0)
    assert magic == 0o411, oct(magic)
    return img[16 + tsize:16 + tsize + dsize], bsize


def c_source():
    data, bsize = segments()
    out = ['/*',
           ' * lddata.c - the initialized data segment of the original MUTOS 1700',
           ' * ld (mutos/mutos_bin/ld.golden.base64.txt): %d bytes, then %d bytes of'
           % (len(data), bsize),
           ' * BSS. Generated by tests/realbin/ldtables.py --c - do not edit;',
           ' * "make check-realbin" checks it is current.',
           ' *',
           ' * The port loads these bytes at address 0 of its memory image',
           ' * (src/mutos_ld/ld.h): crt0\'s words, ld.c\'s data and strings, the',
           ' * libc.a data after them, each at the address the original\'s code',
           ' * uses.',
           ' */',
           '',
           '#include "ld.h"',
           '',
           'const unsigned char ld_data[LD_DSIZE] = {']
    for i in range(0, len(data), 12):
        row = data[i:i + 12]
        out.append('\t' + ' '.join('0x%02x,' % b for b in row)
                   + '\t/* %04x */' % i)
    out.append('};')
    out.append('')
    return '\n'.join(out)


# words among the strings: libp, ofilename, outname, delarg (0022..0029),
# bytrel()'s statics (003a..003f)
WORDS = set(range(0x22, 0x2a)) | set(range(0x3a, 0x40))


def strings():
    data, _ = segments()
    a, hi = LD_DATA
    while a < hi:
        if a in WORDS or data[a] == 0 or (a > 0 and data[a - 1] != 0):
            a += 1
            continue
        e = data.index(b'\0', a)
        s = data[a:e]
        if len(s) >= 2 and all(32 <= c < 127 or c in (9, 10) for c in s):
            print('  %04x %r' % (a, s.decode('latin1')))
        a = e + 1


def main(argv):
    if argv[:1] == ['--c']:
        sys.stdout.write(c_source())
        return 0
    if len(argv) == 2 and argv[0] == '--check-c':
        if open(argv[1]).read() != c_source():
            print('%s is not what ldtables.py --c prints' % argv[1])
            return 1
        print('%s is current' % argv[1])
        return 0
    if argv[:1] == ['--strings']:
        strings()
        return 0
    sys.exit(__doc__.split('Usage:')[1])


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
