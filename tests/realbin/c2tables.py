#!/usr/bin/env python3
"""c2tables.py - the real MUTOS 1700 c2's initialized data, for the port.

The port of c2 (src/mutos_cc/c2port/, "The port of c2" in
docs/devlog/originals_and_ports.md) runs on an image of the original's
64K data segment, so that every address the original computes - also
where it runs past an array (a long operand copied into regs[], a long
first token into oplook()'s tmpop[] and on into refcount()'s labhash[],
repladdr()'s rt1[]/rt2[] into libc.a's BSS and the heap) - reads and
writes what the original reads and writes. This script writes that
segment's initialized part, the binary's own bytes, as C: c2data.c.
Nothing in it is typed by hand. The binary is stripped;
tests/realbin/c2map.txt names its functions and data.

Usage:
    c2tables.py --c                 print c2data.c
    c2tables.py --check-c FILE      check FILE is what --c prints
    c2tables.py --strings           print the strings of c2's data
    c2tables.py --optab             print optab[] and revbr[]
"""
import base64
import os
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..', '..'))
BIN = os.path.join(ROOT, 'mutos_bin', 'c2.golden.base64.txt')

# c2's data: optab[] from 000a, revbr[], isn, lastseg, then the strings
# up to the register-name pointers; libc.a's data begins at 0514
# ("(null)", then the stdio structures, _lastbuf, malloc's words, the
# break)
OPTAB = 0x000a
REVBR = 0x010e
C2_STRINGS = (0x011c, 0x0514)
REGNAMES = 0x04f2


def segments():
    img = base64.b64decode(open(BIN, 'rb').read())
    magic, tsize, dsize, bsize = struct.unpack_from('<4H', img, 0)
    assert magic == 0o411, oct(magic)
    return img[16 + tsize:16 + tsize + dsize], bsize


def c_source():
    data, bsize = segments()
    out = ['/*',
           ' * c2data.c - the initialized data segment of the original MUTOS 1700',
           ' * c2 (mutos_bin/c2.golden.base64.txt): %d bytes, then %d bytes of'
           % (len(data), bsize),
           ' * BSS. Generated by tests/realbin/c2tables.py --c - do not edit;',
           ' * "make check-realbin" checks it is current.',
           ' *',
           ' * The port loads these bytes at address 0 of its memory image',
           ' * (src/mutos_cc/c2port/c2.h): crt0\'s words, optab[], revbr[], the',
           ' * strings, the register names, the libc.a data after them (the',
           ' * stdio structures, the break), each at the address the original\'s',
           ' * code uses.',
           ' */',
           '',
           '#include "c2.h"',
           '',
           'const unsigned char c2_data[C2_DSIZE] = {']
    for i in range(0, len(data), 12):
        row = data[i:i + 12]
        out.append('\t' + ' '.join('0x%02x,' % b for b in row)
                   + '\t/* %04x */' % i)
    out.append('};')
    out.append('')
    return '\n'.join(out)


def cstr(data, a):
    e = data.index(b'\0', a)
    return data[a:e].decode('latin1')


def strings():
    data, _ = segments()
    a, hi = C2_STRINGS
    while a < hi:
        if REGNAMES <= a < REGNAMES + 12 or data[a] == 0 \
                or (a > 0 and data[a - 1] != 0):
            a += 1
            continue
        e = data.index(b'\0', a)
        s = data[a:e]
        if all(32 <= c < 127 or c in (9, 10) for c in s):
            print('  %04x %r' % (a, s.decode('latin1')))
        a = e + 1


def optab():
    data, _ = segments()
    a = OPTAB
    while True:
        p, code = struct.unpack_from('<HH', data, a)
        if p == 0:
            break
        print('  %04x %-8s op %2d subop %3d' % (a, cstr(data, p), code & 0xff,
                                                code >> 8))
        a += 4
    print('  revbr[] at %04x: %s' % (REVBR, list(data[REVBR:REVBR + 10])))
    names = [struct.unpack_from('<H', data, REGNAMES + 2 * i)[0]
             for i in range(6)]
    print('  regnames[] at %04x: %s' % (REGNAMES,
                                         [cstr(data, n) for n in names]))


def main(argv):
    if argv[:1] == ['--c']:
        sys.stdout.write(c_source())
        return 0
    if len(argv) == 2 and argv[0] == '--check-c':
        if open(argv[1]).read() != c_source():
            print('%s is not what c2tables.py --c prints' % argv[1])
            return 1
        print('%s is current' % argv[1])
        return 0
    if argv[:1] == ['--strings']:
        strings()
        return 0
    if argv[:1] == ['--optab']:
        optab()
        return 0
    sys.exit(__doc__.split('Usage:')[1])


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
