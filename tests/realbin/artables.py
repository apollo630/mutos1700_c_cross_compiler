#!/usr/bin/env python3
"""artables.py - the real MUTOS 1700 ar's libc.a error texts, for the port.

The port of ar (src/mutos_ar/) writes "ar write error" through perror(),
and libc.a's perror() prints sys_errlist[errno]: a table of 41 texts the
host's strerror() does not give (MUTOS's own wording, "Not owner",
"Arg list too long"..., the numbers v7's). This script reads the table
out of the binary - the 41 pointers at data address 273c, the count at
278e - and writes it as C: ardata.c. Nothing in it is typed by hand. The
binary is stripped; tests/realbin/armap.txt names its functions and data.

Usage:
    artables.py --c                 print ardata.c
    artables.py --check-c FILE      check FILE is what --c prints
    artables.py --table             print the table as the binary has it
"""
import base64
import os
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..', '..'))
BIN = os.path.join(ROOT, 'mutos', 'mutos_bin', 'ar.golden.base64.txt')

ERRLIST = 0x273c        # sys_errlist[]: pointers, data address
NERR = 0x278e           # sys_nerr


def image():
    """The binary's text and data; a 0407 file's data begins at the
    address the text ends at, so the data is indexed by its address."""
    img = base64.b64decode(open(BIN, 'rb').read())
    magic, tsize, dsize, bsize = struct.unpack_from('<4H', img, 0)
    assert magic == 0o407, oct(magic)
    return img[16 + tsize:16 + tsize + dsize], tsize


def table():
    data, base = image()

    def word(a):
        return struct.unpack_from('<H', data, a - base)[0]

    n = word(NERR)
    texts = []
    for i in range(n):
        p = word(ERRLIST + 2 * i)
        e = data.index(b'\0', p - base)
        texts.append(data[p - base:e].decode('ascii'))
    return texts


def cstr(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def c_source():
    texts = table()
    out = ['/*',
           ' * ardata.c - libc.a\'s sys_errlist[] as the original MUTOS 1700 ar',
           ' * (mutos/mutos_bin/ar.golden.base64.txt) has it linked in: %d texts,'
           % len(texts),
           ' * the table perror() prints from. Generated by',
           ' * tests/realbin/artables.py --c - do not edit; "make check-realbin"',
           ' * checks it is current.',
           ' */',
           '',
           '#include "ar.h"',
           '',
           'const int ar_nerr = %d;' % len(texts),
           '',
           'const char *const ar_errlist[%d] = {' % len(texts)]
    for i, t in enumerate(texts):
        out.append('\t%s,\t/* %d */' % (cstr(t), i))
    out.append('};')
    out.append('')
    return '\n'.join(out)


def main(argv):
    if argv[:1] == ['--c']:
        sys.stdout.write(c_source())
        return 0
    if len(argv) == 2 and argv[0] == '--check-c':
        if open(argv[1]).read() != c_source():
            print('%s is not what artables.py --c prints' % argv[1])
            return 1
        print('%s is current' % argv[1])
        return 0
    if argv[:1] == ['--table']:
        for i, t in enumerate(table()):
            print('%2d %s' % (i, t))
        return 0
    sys.exit(__doc__.split('Usage:')[1])


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
