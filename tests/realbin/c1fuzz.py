# Running one program.
# ---------------------------------------------------------------------

def original_c1(wd, depth):
    """The original c1 on wd/t1, wd/t2: (trees, .s, stderr, status)."""
    out_s = os.path.join(wd, 'orig.s')
    trees = ''
    if depth < 4:
        err = []
        trees, st = c1trees.original_trees(os.path.join(wd, 't1'),
                                           os.path.join(wd, 't2'), err)
        return trees, b'', err[0].encode('latin1'), st
    st, _, err = mutosemu.run_tool('c1', [os.path.join(wd, 't1'),
                                          os.path.join(wd, 't2'), out_s],
                                   cwd=wd, max_insns=MAX_INSNS)
    with open(out_s, 'rb') as f:
        return trees, f.read(), err, st


def port_c1(wd, depth, port):
    if depth < 4:
        trees, rc, err = c1trees.port_trees(os.path.join(wd, 't1'),
                                            os.path.join(wd, 't2'), port)
        return trees, b'', err.encode('latin1'), rc
    out_s = os.path.join(wd, 'port.s')
    p = subprocess.run([port, os.path.join(wd, 't1'), os.path.join(wd, 't2'), out_s],
                       capture_output=True, timeout=60)
    s = open(out_s, 'rb').read() if os.path.exists(out_s) else b''
    return '', s, p.stderr, p.returncode


def past_regname(r):
    """The bytes the original prints for register number r outside 0..7:
    the string at the pointer in the word regname[r] - data 0020 + 2r
    (c1map.txt) - reaches, in the data segment as loaded (None if either
    lies outside it)."""
    img = mutosemu.load_image('c1')
    tsize, dsize = int.from_bytes(img[2:4], 'little'), int.from_bytes(img[4:6], 'little')
    data = img[16 + tsize:16 + tsize + dsize]
    at = 0x20 + 2 * r
    if not 0 <= at <= len(data) - 2:
        return None
    ptr = int.from_bytes(data[at:at + 2], 'little')
    if ptr >= len(data):
        return None
    return data[ptr:data.index(b'\0', ptr)] if b'\0' in data[ptr:] else None


def garbled_after(orig, mine, why):
    """Where the port refuses because the original jumps into the middle
    of an instruction (lconst()'s shifts), the original goes on executing
    whatever bytes follow, and what that does to the output still in its
    stdio buffer (512 bytes: v7's BUFSIZ) is not modelled - one such run
    turned the buffer's first byte into a NUL and ended in "Arg count".
    So only what the original had written out by then must be the
    port's."""
    if 'jumps into an instruction' not in why:
        return False
    flushed = len(mine) & ~511
    return orig[:flushed] == mine[:flushed] and len(orig) >= flushed


def run_one(job):
    idx, src, depth, port, workroot = job
    wd = os.path.join(workroot, 'p%d' % idx)
    os.mkdir(wd)
    with open(os.path.join(wd, 'p.c'), 'w') as f:
        f.write(src)
    p = subprocess.run([CPP, '-P', os.path.join(wd, 'p.c'), os.path.join(wd, 'p.i')],
                       capture_output=True)
    if p.returncode:
        return idx, 'cpp', p.stderr.decode('latin1')[-200:]
    try:
        st, _, err = mutosemu.run_tool('c0', [os.path.join(wd, 'p.i'),
                                              os.path.join(wd, 't1'),
                                              os.path.join(wd, 't2')],
                                       cwd=wd, max_insns=MAX_INSNS)
    except RuntimeError as e:
        return idx, 'c0', str(e)
    if st != 0:
        return idx, 'c0', err.decode('latin1').strip().splitlines()[-1:] or ['?']
    try:
        o = original_c1(wd, depth)
    except RuntimeError as e:
        o = e
    try:
        m = port_c1(wd, depth, port)
    except subprocess.TimeoutExpired:
        return idx, 'DIFF', 'the port did not finish (timeout)'
    if isinstance(o, RuntimeError):
        # the original did not finish (it jumped into data, or loops):
        # the port must have refused
        if m[3] == 2:
            return idx, 'orig', 'the original does not finish, refused: %s' % \
                m[2].decode('latin1').strip().splitlines()[-1]
        return idx, 'DIFF', 'the original does not finish (%s), the port does (exit %d)' % (
            o, m[3])
    if m[3] == 2:
        why = m[2].decode('latin1').strip().splitlines()[-1:]
        if depth >= 4 and not o[1].startswith(m[1]) and \
                not garbled_after(o[1], m[1], ' '.join(why)):
            return idx, 'DIFF', 'refused, but the output before differs: %s' % why
        if depth >= 4 and 'regname' in ' '.join(why):
            # the original's next line must hold what it takes for the
            # register's name: the string regname[r]'s word points at
            nxt = o[1][len(m[1]):].split(b'\n', 1)[0]
            r = re.search(r'regname\[\], (-?\d+)', ' '.join(why))
            name = past_regname(int(r.group(1))) if r else None
            if name is None or name not in nxt:
                return idx, 'DIFF', 'refused for register %s outside regname[], but the ' \
                    'original wrote %r there' % (r.group(1) if r else '?', nxt)
        return idx, 'refused', why
    if depth < 4:
        a = c1trees.blocks(o[0], depth)
        b = c1trees.blocks(m[0], depth)
        for i, (x, y) in enumerate(zip(a, b)):
            if x != y:
                return idx, 'DIFF', 'tree %d (%s)\n--- original\n%s--- port\n%s' % (
                    i, x[0], x[1], y[1])
        if len(a) < len(b) and o[2].decode('latin1').endswith('Missing temp file\n'):
            # the original's argv was overwritten on the way: its stack
            # smashed by its code generation (depth 4 compares what it
            # wrote up to there)
            return idx, 'orig-broken', o[2].decode('latin1').strip().splitlines()[-2:]
        if len(a) != len(b):
            return idx, 'DIFF', '%d trees, port %d (exit %d): %s' % (
                len(a), len(b), m[3], m[2].decode('latin1')[-300:])
        return idx, 'same', ''
    if o[1:] != m[1:]:
        detail = []
        if o[3] != m[3]:
            detail.append('exit %d, port %d' % (o[3], m[3]))
        if o[2] != m[2]:
            detail.append('stderr:\n%s--- port\n%s' % (o[2].decode('latin1'),
                                                     m[2].decode('latin1')))
        if o[1] != m[1]:
            ol, ml = o[1].decode('latin1').split('\n'), m[1].decode('latin1').split('\n')
            for i, (x, y) in enumerate(zip(ol, ml)):
                if x != y:
                    detail.append('.s line %d: %r, port %r' % (i + 1, x, y))
                    break
            else:
                detail.append('.s: %d lines, port %d' % (len(ol), len(ml)))
        return idx, 'DIFF', '\n'.join(detail)
    return idx, 'same', ''


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    ap.add_argument('-n', '--count', type=int, default=200)
    ap.add_argument('-s', '--seed', type=int, default=1)
    ap.add_argument('-j', '--jobs', type=int, default=os.cpu_count() or 2)
    ap.add_argument('--depth', type=int, default=4, choices=(1, 2, 4))
    ap.add_argument('--port', default=PORT)
    ap.add_argument('--keep', help='directory to save differing programs in')
    ap.add_argument('--show', type=int, default=3,
                    help='how many differences to print in full')
    ap.add_argument('--gen', choices=('c1fuzz', 'fuzz_c', 'lconst'), default='c1fuzz',
                    help="the program generator: this script's own, "
                    "tests/mutos_cc/fuzz/fuzz_c.py's (arrays, scopes, no floats), or "
                    "long constant arithmetic (lconst())")
    args = ap.parse_args()
    rnd = random.Random(args.seed)
    if args.gen == 'fuzz_c':
        sys.path.insert(0, os.path.join(ROOT, 'tests', 'mutos_cc', 'fuzz'))
        import fuzz_c     # noqa: E402
        progs = [fuzz_c.generate(rnd, True, rnd.random() < 0.5)[0]
                 for _ in range(args.count)]
    elif args.gen == 'lconst':
        progs = [lconst_program(rnd) for _ in range(args.count)]
    else:
        progs = [Gen(rnd).program() for _ in range(args.count)]
    counts, reasons, diffs = {}, {}, []
    with tempfile.TemporaryDirectory(prefix='c1fuzz.') as workroot:
        jobs = [(i, progs[i], args.depth, args.port, workroot) for i in range(args.count)]
        with concurrent.futures.ProcessPoolExecutor(args.jobs) as ex:
            for idx, kind, detail in ex.map(run_one, jobs):
                counts[kind] = counts.get(kind, 0) + 1
                if kind in ('c0', 'refused', 'cpp', 'orig', 'orig-broken'):
                    key = '%s: %s' % (kind, detail if isinstance(detail, str)
                                      else ' '.join(detail))
                    # the line number apart: one reason, one count
                    key = re.sub(r'^(\w[\w-]*: )-?\d+: ', r'\1', key)
                    key = key.replace(' - the original traps or depends on state '
                                      'the port does not model here; refused', '')
                    key = key[:120]
                    reasons[key] = reasons.get(key, 0) + 1
                if kind == 'orig' and args.keep:
                    # the original did not finish: kept to be looked at
                    shutil.copytree(os.path.join(workroot, 'p%d' % idx),
                                    os.path.join(args.keep, 'orig.s%d.p%d' % (args.seed, idx)),
                                    dirs_exist_ok=True)
                if kind == 'DIFF':
                    diffs.append((idx, detail))
                    if args.keep:
                        os.makedirs(args.keep, exist_ok=True)
                        shutil.copytree(os.path.join(workroot, 'p%d' % idx),
                                        os.path.join(args.keep, 's%d.p%d' % (args.seed, idx)),
                                        dirs_exist_ok=True)
    for idx, detail in diffs[:args.show]:
        print('--- program %d differs:\n%s\n%s' % (idx, progs[idx], detail))
    for idx, detail in diffs[args.show:]:
        print('program %d differs: %s' % (idx, detail.split('\n')[0]))
    for k, v in sorted(reasons.items(), key=lambda kv: -kv[1])[:15]:
        print('  %5d  %s' % (v, k))
    print('c1fuzz: %d programs (%s), seed %d, depth %d: %d same, %d DIFFERENT, '
          '%d refused by the port, %d refused by c0, %d other' % (
              args.count, args.gen, args.seed, args.depth, counts.get('same', 0),
              counts.get('DIFF', 0), counts.get('refused', 0), counts.get('c0', 0),
              sum(v for k, v in counts.items()
                  if k not in ('same', 'DIFF', 'refused', 'c0'))))
    return 1 if diffs else 0


if __name__ == '__main__':
    sys.exit(main())
