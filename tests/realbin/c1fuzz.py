#!/usr/bin/env python3
"""c1fuzz.py - differential fuzzing of the c1 port against the original c1.

The c1 port (src/mutos_cc/c1port/, docs/C1_PORT_PLAN.md) must do what the
original binary does for any input, not only for the goldens. This script
generates random K&R programs over every type c1 handles - char, int,
unsigned, long, float, double, pointers, arrays, a structure with
bit-fields, register variables, calls - and runs each through
mutos_cpp -P and the original c0 (emulated, so every program gets the
real intermediate files), then through the original c1 (emulated) and
the port, and compares them:

    --depth 2   the expression trees after optim() (and before, depth 1),
                as tests/realbin/c1trees.py takes them;
    --depth 4   the whole output: the .s file, the messages on stderr and
                the exit status (the default).

There is no semantic check here - the original is the oracle; c0's
refusals (a program the generator got wrong) are counted and skipped,
and so are programs the port refuses on purpose (c1trap(), exit status
2: state it does not model) - those are listed by reason.

Usage:
    c1fuzz.py [-n COUNT] [-s SEED] [-j JOBS] [--depth 1|2|4] [--keep DIR]
              [--show N] [--gen c1fuzz|fuzz_c|lconst]

Exit status 1 if any program differs. A fixed seed gives the same
programs every time.

Requires the Python module "unicorn" (pip install unicorn).
"""
import argparse
import concurrent.futures
import os
import random
import re
import shutil
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import mutosemu       # noqa: E402
import c1trees        # noqa: E402

ROOT = os.path.normpath(os.path.join(HERE, '..', '..'))
CPP = os.path.join(ROOT, 'src', 'mutos_cpp', 'mutos_cpp')
PORT = c1trees.PORT
MAX_INSNS = 400_000_000

# ---------------------------------------------------------------------
# The program generator. Expressions are generated by type class:
#   c char, i int, u unsigned, l long, f float, d double,
#   pi int *, pc char *, ps struct s *.
# Each generator returns C text; lvalues are tracked separately so that
# assignments, ++/-- and & only apply to them.
# ---------------------------------------------------------------------

INTLIKE = ('c', 'i', 'u')
ARITH = ('c', 'i', 'u', 'l', 'f', 'd')
CTYPE = {'c': 'char', 'i': 'int', 'u': 'unsigned', 'l': 'long',
         'f': 'float', 'd': 'double'}

GLOBALS = """\
int gi, gj, ga[10];
char gc, gca[12];
unsigned gu;
long gl, gla[4];
float gf, gfa[3];
double gd;
int *gp;
char *gcp;
struct s {
	int a;
	char b;
	long c;
	int f1:3;
	unsigned f2:5;
	int f3:8;
	double d;
	struct s *next;
	int e[3];
} gs, *gsp;
static int si1;
static long sl1;
static double sd1;
int ig();
long lg();
double dg();
float fg();
char *cg();
"""


class Gen:
    def __init__(self, rnd):
        self.r = rnd
        # name -> type class, per kind of storage
        self.vars = {}

    def pick(self, seq):
        return self.r.choice(seq)

    def chance(self, p):
        return self.r.random() < p

    # -- leaves ------------------------------------------------------------
    def lvalues(self, t):
        """lvalue texts of type class t."""
        out = [n for n, ty in self.vars.items() if ty == t]
        if t == 'i':
            out += ['gi', 'gj', 'si1', 'ga[%s]' % self.index(), 'gs.a',
                    'gsp->a', 'gs.f1', 'gsp->f3', '*gp', 'gp[%s]' % self.index(),
                    'gs.e[%s]' % self.index(), 'gsp->next->a']
        elif t == 'c':
            out += ['gc', 'gca[%s]' % self.index(), 'gs.b', 'gsp->b', '*gcp',
                    'gcp[%s]' % self.index()]
        elif t == 'u':
            out += ['gu', 'gs.f2', 'gsp->f2']
        elif t == 'l':
            out += ['gl', 'sl1', 'gla[%s]' % self.index(), 'gs.c', 'gsp->c']
        elif t == 'f':
            out += ['gf', 'gfa[%s]' % self.index()]
        elif t == 'd':
            out += ['gd', 'sd1', 'gs.d', 'gsp->d']
        elif t == 'pi':
            out += ['gp']
        elif t == 'pc':
            out += ['gcp']
        elif t == 'ps':
            out += ['gsp', 'gs.next', 'gsp->next']
        return out

    def index(self):
        r = self.r.random()
        if r < 0.4:
            return str(self.r.randint(0, 2))
        ints = [n for n, ty in self.vars.items() if ty in ('i', 'c')]
        if ints and r < 0.8:
            return self.pick(ints)
        return 'gi'

    def const(self, t):
        r = self.r
        if t in ('c', 'i'):
            return self.pick(['0', '1', '2', '3', '4', '7', '8', '16', '100',
                              '127', '128', '255', '256', '1000', '32767',
                              str(r.randint(0, 40)), '0377', '0x7f00',
                              "'a'", "'\\n'"])
        if t == 'u':
            return self.pick(['1', '2', '8', '40000', '0177777', '65535'])
        if t == 'l':
            return self.pick(['0L', '1L', '2L', '100000L', '65536L', '070000L',
                              '-1L', '32768L', '2147483647L', '3'])
        if t == 'f':
            return self.pick(['1.0', '0.5', '2.5', '0.1', '100.0', '3.0', '1e10'])
        if t == 'd':
            return self.pick(['1.0', '0.1', '3.14159265358979', '2.0', '1e-5',
                              '0.0', '12345.678'])
        return '0'

    def leaf(self, t):
        if t in ARITH and self.chance(0.25):
            return self.const(t)
        if t == 'pi':
            return self.pick(['gp', '&gi', 'ga', '&ga[%s]' % self.index(),
                              '&gs.a', 'gs.e', '&gsp->a'] +
                             [n for n, ty in self.vars.items() if ty == 'pi'])
        if t == 'pc':
            return self.pick(['gcp', 'gca', '&gc', '"str"', 'cg()', '&gs.b'] +
                             [n for n, ty in self.vars.items() if ty == 'pc'])
        if t == 'ps':
            return self.pick(['gsp', '&gs', 'gsp->next'])
        return self.pick(self.lvalues(t))

    # -- expressions ---------------------------------------------------
    def expr(self, t, depth):
        if depth <= 0 or self.chance(0.2):
            return self.leaf(t)
        if t in INTLIKE:
            return self.intexpr(t, depth)
        if t == 'l':
            return self.longexpr(depth)
        if t in ('f', 'd'):
            return self.fltexpr(t, depth)
        return self.ptrexpr(t, depth)

    def sub(self, depth):
        """An operand of some arithmetic type."""
        return self.expr(self.pick(ARITH), depth - 1)

    def assign(self, t, depth):
        lv = self.pick(self.lvalues(t))
        if t in ('f', 'd'):
            ops = ['=', '=+', '=-', '=*', '=/']
        elif t in ('pi', 'pc', 'ps'):
            ops = ['=']
        else:
            ops = ['=', '=+', '=-', '=*', '=/', '=%', '=&', '=|', '=^',
                   '=<<', '=>>']
        op = self.pick(ops)
        if t in ('pi', 'pc', 'ps'):
            rhs = self.expr(t, depth - 1)
        elif op in ('=<<', '=>>'):
            rhs = self.expr(self.pick(INTLIKE), depth - 1)
        elif op in ('=%', '=&', '=|', '=^'):
            rhs = self.expr(self.pick(INTLIKE + ('l',)), depth - 1)
        else:
            rhs = self.sub(depth)
        return '(%s %s %s)' % (lv, op, rhs)

    def incdec(self, t):
        lv = self.pick(self.lvalues(t))
        return self.pick(['%s++', '%s--', '++%s', '--%s']) % lv

    def intexpr(self, t, depth):
        r = self.r.random()
        a = lambda: self.expr(self.pick(INTLIKE), depth - 1)
        if r < 0.30:
            op = self.pick(['+', '-', '*', '/', '%', '<<', '>>', '&', '|', '^'])
            return '(%s %s %s)' % (a(), op, a())
        if r < 0.40:
            x, y = self.sub(depth), self.sub(depth)
            return '(%s %s %s)' % (x, self.pick(['<', '>', '<=', '>=', '==', '!=']), y)
        if r < 0.45:
            p = self.pick(['pi', 'pc'])
            return '(%s %s %s)' % (self.expr(p, depth - 1),
                                   self.pick(['<', '>', '==', '!=']),
                                   self.expr(p, depth - 1))
        if r < 0.52:
            return '(%s %s %s)' % (self.sub(depth), self.pick(['&&', '||']),
                                   self.sub(depth))
        if r < 0.58:
            return '(%s%s)' % (self.pick(['-', '~', '!']), a())
        if r < 0.63:
            return '(%s ? %s : %s)' % (self.sub(depth), a(), a())
        if r < 0.73:
            return self.assign(t, depth)
        if r < 0.78:
            return self.incdec(t)
        if r < 0.85:
            return '((%s)%s)' % (CTYPE[t], self.sub(depth))
        if r < 0.90:
            return 'ig(%s)' % ', '.join(self.sub(depth) for _ in range(self.r.randint(0, 3)))
        if r < 0.95:
            p = self.pick(['pi', 'pc'])
            return '(%s - %s)' % (self.expr(p, depth - 1), self.expr(p, depth - 1))
        return '(%s, %s)' % (self.sub(depth), a())

    def longexpr(self, depth):
        r = self.r.random()
        lop = lambda: self.expr(self.pick(('l', 'l', 'i', 'u', 'c')), depth - 1)
        if r < 0.40:
            op = self.pick(['+', '-', '*', '/', '%', '&', '|', '^'])
            return '(%s %s %s)' % (lop(), op, lop())
        if r < 0.50:
            return '(%s %s %s)' % (lop(), self.pick(['<<', '>>']),
                                   self.expr(self.pick(INTLIKE), depth - 1))
        if r < 0.60:
            return '(%s%s)' % (self.pick(['-', '~']), lop())
        if r < 0.72:
            return self.assign('l', depth)
        if r < 0.77:
            return self.incdec('l')
        if r < 0.87:
            return '((long)%s)' % self.sub(depth)
        if r < 0.92:
            return 'lg(%s)' % self.sub(depth)
        return '(%s ? %s : %s)' % (self.sub(depth), lop(), lop())

    def fltexpr(self, t, depth):
        r = self.r.random()
        fop = lambda: self.expr(self.pick(('f', 'd', 'i', 'l', 'c')), depth - 1)
        if r < 0.45:
            return '(%s %s %s)' % (fop(), self.pick(['+', '-', '*', '/']), fop())
        if r < 0.52:
            return '(-%s)' % fop()
        if r < 0.67:
            return self.assign(t, depth)
        if r < 0.80:
            return '((%s)%s)' % (CTYPE[t], self.sub(depth))
        if r < 0.88:
            return self.pick(['dg(%s)', 'fg(%s)']) % self.sub(depth)
        return '(%s ? %s : %s)' % (self.sub(depth), fop(), fop())

    def ptrexpr(self, t, depth):
        r = self.r.random()
        if t == 'ps':
            return self.pick(['gsp', '&gs', 'gsp->next', '(gsp + 1)',
                              self.assign('ps', depth)])
        if r < 0.35:
            return '(%s %s %s)' % (self.expr(t, depth - 1), self.pick(['+', '-']),
                                   self.expr(self.pick(INTLIKE), depth - 1))
        if r < 0.50:
            return self.assign(t, depth)
        if r < 0.60:
            return self.incdec(t)
        if r < 0.70:
            return '(%s ? %s : %s)' % (self.sub(depth), self.expr(t, depth - 1),
                                       self.expr(t, depth - 1))
        return self.leaf(t)

    # -- statements and the program ------------------------------------
    def stmt(self, depth):
        r = self.r.random()
        t = self.pick(ARITH + ('pi', 'pc'))
        if r < 0.55:
            return '\t%s;' % self.expr(t, depth)
        if r < 0.70:
            body = '\t\t%s;' % self.expr(self.pick(ARITH), depth - 1)
            s = '\tif (%s)\n%s' % (self.expr(self.pick(ARITH + ('pi',)), depth), body)
            if self.chance(0.4):
                s += '\n\telse\n\t\t%s;' % self.expr(self.pick(ARITH), depth - 1)
            return s
        if r < 0.78:
            return '\twhile (%s)\n\t\t%s;' % (self.expr(self.pick(ARITH), depth),
                                              self.expr(self.pick(ARITH), depth - 1))
        if r < 0.86:
            cases = sorted(set(self.r.randint(-3, 40) for _ in range(self.r.randint(1, 12))))
            lines = ['\tswitch (%s) {' % self.expr(self.pick(INTLIKE), depth)]
            for c in cases:
                lines.append('\tcase %d:\n\t\t%s;\n\t\tbreak;'
                             % (c, self.expr(self.pick(ARITH), depth - 1)))
            if self.chance(0.5):
                lines.append('\tdefault:\n\t\t%s;' % self.expr('i', depth - 1))
            lines.append('\t}')
            return '\n'.join(lines)
        return '\treturn(%s);' % self.expr(self.ret, depth)

    def function(self, name):
        r = self.r
        self.vars = {}
        decls = []
        params = []
        for p, ty in (('a', 'i'), ('b', 'pc'), ('x', 'd'), ('y', 'l'), ('q', 'c')):
            if self.chance(0.5):
                params.append(p)
                self.vars[p] = ty
        pdecl = []
        for p in params:
            ty = self.vars[p]
            pdecl.append({'i': 'int %s;', 'pc': 'char *%s;', 'd': 'double %s;',
                          'l': 'long %s;', 'c': 'char %s;'}[ty] % p)
        regs = 0
        for n, ty in (('i', 'i'), ('j', 'i'), ('k', 'c'), ('u', 'u'), ('l', 'l'),
                      ('m', 'l'), ('f', 'f'), ('d', 'd'), ('e', 'd'), ('p', 'pi'),
                      ('s', 'pc'), ('ri', 'i'), ('rj', 'i'), ('rp', 'pi'),
                      ('rc', 'pc'), ('rk', 'c')):
            if not self.chance(0.6):
                continue
            reg = n.startswith('r') and regs < 3 and self.chance(0.8)
            if reg:
                regs += 1
            self.vars[n] = ty
            decls.append('\t%s%s;' % ('register ' if reg else '',
                                       {'i': 'int %s', 'c': 'char %s', 'u': 'unsigned %s',
                                        'l': 'long %s', 'f': 'float %s', 'd': 'double %s',
                                        'pi': 'int *%s', 'pc': 'char *%s'}[ty] % n))
        if self.chance(0.3):
            decls.append('\tint arr[%d];' % r.randint(2, 70))
            self.vars['arr[1]'] = 'i'
        self.ret = self.pick(('i', 'i', 'l', 'd', 'c'))
        rtype = {'i': '', 'l': 'long ', 'd': 'double ', 'c': 'char '}[self.ret]
        body = [self.stmt(r.randint(1, 4)) for _ in range(r.randint(2, 8))]
        return '%s%s(%s)\n%s\n{\n%s\n%s\n}\n' % (
            rtype, name, ', '.join(params), '\n'.join(pdecl), '\n'.join(decls),
            '\n'.join(body))

    def program(self):
        return GLOBALS + '\n' + '\n'.join(self.function('f%d' % i)
                                          for i in range(self.r.randint(1, 3)))


# ---------------------------------------------------------------------
# --gen lconst: long constant arithmetic, which c1's lconst() folds -
# through libc.a's aldiv, alrem and almul (c1port/c1lib.c) - at the
# edges of their short and long paths.
# ---------------------------------------------------------------------

LEDGES = (0, 1, 2, 3, 7, 255, 256, 32767, 32768, 32769, 65535, 65536, 65537,
          0x17fff, 0x18000, 0x18001, 0x1ffff, 0x20000, 0x7fff0000, 0x7fffffff,
          0x80000000, 0xffff0000, 0xffff8000, 0xffffffff, 0xfffffffe)


def lconst_text(r):
    """A long constant's text: decimal, octal or hex, an int one widened
    (no L) where it fits one word, or a negation."""
    v = r.choice(LEDGES) if r.random() < 0.7 else r.getrandbits(r.choice((8, 16, 17, 31, 32)))
    v &= 0xFFFFFFFF
    sv = v - (1 << 32) if v & 0x80000000 else v
    k = r.random()
    if 0 <= sv <= 32767 and k < 0.3:
        return '%d' % sv                       # an int, widened
    if v <= 0xFFFF and k < 0.45:
        return '0%o' % v if r.random() < 0.5 else '0x%x' % v   # an int (65535 is -1)
    if sv < 0 and sv != -(1 << 31) and k < 0.8:
        return '(-%dL)' % -sv
    return '0x%xL' % v if r.random() < 0.5 else '%dL' % v


def lconst_program(r):
    lines = ['long gl, gm;', 'f()', '{']
    for _ in range(r.randint(20, 120)):
        op = r.choice('/%/%/%*+-&|^')
        lines.append('\tgl = %s %s %s;' % (lconst_text(r), op, lconst_text(r)))
    lines.append('}')
    return '\n'.join(lines) + '\n'


