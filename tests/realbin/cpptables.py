#!/usr/bin/env python3
"""cpptables.py - the real MUTOS 1700 cpp's initialized data, for the port.

The port of cpp (src/mutos_cpp/, the "cpp" section of
docs/devlog/originals_and_ports.md) runs on an image of the original's 64K
data segment, so that every address the original computes - including
the ones it computes by mistake (fastab[] indexed with a byte 0200..0377,
dirs[10] written by a ninth -I) - reads what the original reads. This
script writes that segment's initialized part, the binary's own bytes,
as C: cppdata.c. Nothing in it is typed by hand. The binary still has its
symbol table (267 symbols), which names the functions and the data.

Usage:
    cpptables.py --c                 print cppdata.c
    cpptables.py --check-c FILE      check FILE is what --c prints
    cpptables.py --symbols           print the symbol table by address
    cpptables.py --tables            print the strings, yylex()'s tables
                                     and yacc's tables in readable form
"""
import base64
import os
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..', '..'))
BIN = os.path.join(ROOT, 'mutos', 'mutos_bin', 'cpp.golden.base64.txt')


def image():
    img = base64.b64decode(open(BIN, 'rb').read())
    magic, tsize, dsize, bsize, ssize = struct.unpack_from('<5H', img, 0)
    assert magic == 0o411, oct(magic)
    return img, tsize, dsize, bsize, ssize


def segments():
    img, tsize, dsize, bsize, _ = image()
    return img[16 + tsize:16 + tsize + dsize], bsize


def symbols():
    """[(type, value, name)] of the binary's symbol table."""
    img, tsize, dsize, _, ssize = image()
    tab = img[16 + tsize + dsize:16 + tsize + dsize + ssize]
    out = []
    for i in range(0, len(tab), 12):
        name = tab[i:i + 8].split(b'\0')[0].decode('latin1')
        out.append((tab[i + 8], struct.unpack_from('<H', tab, i + 10)[0], name))
    return out


def c_source():
    data, bsize = segments()
    out = ['/*',
           ' * cppdata.c - the initialized data segment of the original MUTOS 1700',
           ' * cpp (mutos/mutos_bin/cpp.golden.base64.txt): %d bytes, then %d bytes of'
           % (len(data), bsize),
           ' * BSS. Generated by tests/realbin/cpptables.py --c - do not edit;',
           ' * "make check-realbin" checks it is current.',
           ' *',
           ' * The port loads these bytes at address 0 of its memory image',
           ' * (src/mutos_cpp/cpp.h): yacc\'s yydef[], cpp.c\'s and yylex.c\'s data',
           ' * and strings, yacc\'s other tables, the libc.a data after them and',
           ' * crt0\'s words below them, each at the address the original\'s code',
           ' * uses.',
           ' */',
           '',
           '#include "cpp.h"',
           '',
           'const unsigned char cpp_data[CPP_DSIZE] = {']
    for i in range(0, len(data), 12):
        row = data[i:i + 12]
        out.append('\t' + ' '.join('0x%02x,' % b for b in row)
                   + '\t/* %04x */' % i)
    out.append('};')
    out.append('')
    return '\n'.join(out)


def print_symbols():
    kind = {0: 'U', 1: 'A', 2: 'T', 3: 'D', 4: 'B'}
    for t, v, n in sorted(symbols(), key=lambda s: (s[0] & 0x1f, s[1])):
        print('%s%s %04x %s' % (kind.get(t & 0x1f, '?'),
                                'E' if t & 0x20 else ' ', v, n))


def tables():
    data, _ = segments()
    w = lambda a: struct.unpack_from('<h', data, a)[0]
    s = lambda a: data[a:data.index(b'\0', a)]
    print('strings (00ae..03e1, 0900..09a5):')
    for lo, hi in ((0xae, 0x3e2), (0x900, 0x9a6)):
        a = lo
        while a < hi:
            e = data.index(b'\0', a)
            print('  %04x %r' % (a, data[a:e].decode('latin1')))
            a = e + 1
    print('yylex: op2 (03fe) / val2 (040e):',
          ', '.join('%s=%d' % (s(w(0x3fe + 2 * i) & 0xffff).decode(),
                              w(0x40e + 2 * i)) for i in range(8)))
    print('yylex: opc (041e) ->', repr(s(w(0x41e) & 0xffff).decode('latin1')))
    for name, lo, hi in (('yydef', 0x0a, 0x86), ('yyexca', 0x420, 0x4ac),
                         ('yyact', 0x4ac, 0x782), ('yypact', 0x782, 0x7fe),
                         ('yypgo', 0x7fe, 0x806), ('yyr1', 0x806, 0x842),
                         ('yyr2', 0x842, 0x87e), ('yychk', 0x87e, 0x8fa)):
        vals = [w(a) for a in range(lo, hi, 2)]
        print('%s (%04x), %d entries:' % (name, lo, len(vals)))
        for i in range(0, len(vals), 16):
            print('  ' + ' '.join('%5d' % v for v in vals[i:i + 16]))


def main(argv):
    if argv[:1] == ['--c']:
        sys.stdout.write(c_source())
        return 0
    if len(argv) == 2 and argv[0] == '--check-c':
        if open(argv[1]).read() != c_source():
            print('%s is not what cpptables.py --c prints' % argv[1])
            return 1
        print('%s is current' % argv[1])
        return 0
    if argv[:1] == ['--symbols']:
        print_symbols()
        return 0
    if argv[:1] == ['--tables']:
        tables()
        return 0
    sys.exit(__doc__.split('Usage:')[1])


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
