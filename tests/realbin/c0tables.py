#!/usr/bin/env python3
"""c0tables.py - the real MUTOS 1700 c0's initialized data, for the port.

The port of c0 (src/mutos_cc/c0port/, docs/C0_PORT_PLAN.md) runs on an
image of the original's 64K data segment, so that every address the
original computes - including the ones it computes by mistake (a null
tree's fields, ctab[] past its end) - reads what the original reads.
This script writes that segment's initialized part, the binary's own
bytes, as C: c0data.c. Nothing in it is typed by hand.

Usage:
    c0tables.py --c                 print c0data.c
    c0tables.py --check-c FILE      check FILE is what --c prints
    c0tables.py --tables            print the tables in readable form
                                    (opdope, cvtab, cvntab, ctab, kwtab)
"""
import base64
import os
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..', '..'))
BIN = os.path.join(ROOT, 'mutos', 'mutos_bin', 'c0.golden.base64.txt')


def segments():
    img = base64.b64decode(open(BIN, 'rb').read())
    magic, tsize, dsize, bsize = struct.unpack_from('<4H', img, 0)
    assert magic == 0o411, oct(magic)
    return img[16 + tsize:16 + tsize + dsize], bsize


def c_source():
    data, bsize = segments()
    out = ['/*',
           ' * c0data.c - the initialized data segment of the original MUTOS 1700',
           ' * c0 (mutos/mutos_bin/c0.golden.base64.txt): %d bytes, then %d bytes of'
           % (len(data), bsize),
           ' * BSS. Generated by tests/realbin/c0tables.py --c - do not edit;',
           ' * "make check-realbin" checks it is current.',
           ' *',
           ' * The port loads these bytes at address 0 of its memory image',
           ' * (c0port/c0.h): the strings, kwtab, opdope, cvtab, cvntab, ctab, the',
           ' * libc.a data after them and crt0\'s words below them, each at the',
           ' * address the original\'s code uses.',
           ' */',
           '',
           '#include "c0.h"',
           '',
           'const unsigned char c0_data[C0_DSIZE] = {']
    for i in range(0, len(data), 12):
        row = data[i:i + 12]
        out.append('\t' + ' '.join('0x%02x,' % b for b in row)
                   + '\t/* %04x */' % i)
    out.append('};')
    out.append('')
    return '\n'.join(out)


def tables():
    data, _ = segments()
    w = lambda a: struct.unpack_from('<H', data, a)[0]
    s = lambda a: data[a:data.index(b'\0', a)].decode('latin1')
    print('kwtab (001c):')
    a = 0x1c
    while w(a):
        print('  %-10s %d' % (s(w(a)), w(a + 2)))
        a += 4
    print('opdope (08ec): op: octal')
    for op in range(111):
        v = w(0x8ec + 2 * op)
        if v:
            print('  %3d: %06o' % (op, v))
    print('cvtab (09ca): rows lintyp(t1) char int float long other,'
          ' columns lintyp(t2); leftc<<5 | cvn')
    for r in range(5):
        print('  ' + ' '.join('%2d<<5|%-2d' % (v >> 5, v & 31) for v in
                              (w(0x9ca + 10 * r + 2 * c) for c in range(5))))
    print('cvntab (09fc):', list(data[0x9fc:0xa0c]))
    print('ctab (0a0c):', list(data[0xa0c:0xa8c]))


def main(argv):
    if argv == ['--c']:
        sys.stdout.write(c_source())
        return 0
    if len(argv) == 2 and argv[0] == '--check-c':
        with open(argv[1]) as f:
            if f.read() != c_source():
                print('c0 data: %s is not current - regenerate it with '
                      'tests/realbin/c0tables.py --c' % argv[1])
                return 1
        print('c0 data: %s up to date' % os.path.basename(argv[1]))
        return 0
    if argv == ['--tables']:
        tables()
        return 0
    sys.exit(__doc__.split('Usage:')[1])


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
