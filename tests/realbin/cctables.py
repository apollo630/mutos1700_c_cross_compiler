#!/usr/bin/env python3
"""cctables.py - the real MUTOS 1700 cc's initialized segment, for the port.

The port of cc (src/mutos_cc/ccport/, "The port of cc" in
docs/devlog/originals_and_ports.md) runs on an image of the original's
64K segment, so that every address the original computes - also where
it runs past an array (a -K or -B argument copied over the strings after
kopt[] or pass0[], a file name copied past ts[] into av[], more than 50
arguments for ld written past av[] into clist[] and llist[]) or reads
through a wild pointer (copy(tmp0) with tmp0 still 0 reads crt0's code
at address 0) - reads and writes what the original reads and writes. cc
is 0407: text and data in one segment, the data at 1f5a. This script
writes the segment's initialized part, the binary's own text and data
bytes, as C: ccdata.c. Nothing in it is typed by hand. The binary is
stripped; tests/realbin/ccmap.txt names its functions and data.

Usage:
    cctables.py --c                 print ccdata.c
    cctables.py --check-c FILE      check FILE is what --c prints
    cctables.py --strings           print the strings of cc.o's data
"""
import base64
import os
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..', '..'))
BIN = os.path.join(ROOT, 'mutos_bin', 'cc.golden.base64.txt')

# cc.o's data: from tsa (after crt0's words) to libc.a's "(null)"
CC_DATA = (0x1f64, 0x2200)


def segment():
    img = base64.b64decode(open(BIN, 'rb').read())
    magic, tsize, dsize, bsize = struct.unpack_from('<4H', img, 0)
    assert magic == 0o407, oct(magic)
    return img[16:16 + tsize + dsize], tsize, dsize, bsize


def c_source():
    seg, tsize, dsize, bsize = segment()
    out = ['/*',
           ' * ccdata.c - the initialized segment of the original MUTOS 1700 cc',
           ' * (mutos_bin/cc.golden.base64.txt, 0407): %d bytes of text, %d of'
           % (tsize, dsize),
           ' * data, then %d bytes of BSS. Generated by tests/realbin/cctables.py'
           % bsize,
           ' * --c - do not edit; "make check-realbin" checks it is current.',
           ' *',
           ' * The port loads these bytes at address 0 of its memory image',
           ' * (src/mutos_cc/ccport/cc.h): the text, which the port only reads',
           ' * (where the original reads it through a wild pointer), then crt0\'s',
           ' * words, cc.c\'s data and strings and the libc.a data after them, each',
           ' * at the address the original\'s code uses.',
           ' */',
           '',
           '#include "cc.h"',
           '',
           'const unsigned char cc_seg[CC_SEGSIZE] = {']
    for i in range(0, len(seg), 12):
        row = seg[i:i + 12]
        out.append('\t' + ' '.join('0x%02x,' % b for b in row)
                   + '\t/* %04x */' % i)
    out.append('};')
    out.append('')
    return '\n'.join(out)


# words among the strings: tsa, tsp (1f64..1f67), pref (1fd6)
WORDS = set(range(0x1f64, 0x1f68)) | {0x1fd6, 0x1fd7}


def strings():
    seg, _, _, _ = segment()
    a, hi = CC_DATA
    while a < hi:
        if a in WORDS or seg[a] == 0 or (seg[a - 1] != 0
                                         and a - 1 not in WORDS):
            a += 1
            continue
        e = seg.index(b'\0', a)
        s = seg[a:e]
        if len(s) >= 1 and all(32 <= c < 127 or c in (9, 10) for c in s):
            print('  %04x %r' % (a, s.decode('latin1')))
        a = e + 1


def main(argv):
    if argv[:1] == ['--c']:
        sys.stdout.write(c_source())
        return 0
    if len(argv) == 2 and argv[0] == '--check-c':
        if open(argv[1]).read() != c_source():
            print('%s is not what cctables.py --c prints' % argv[1])
            return 1
        print('%s is current' % argv[1])
        return 0
    if argv[:1] == ['--strings']:
        strings()
        return 0
    sys.exit(__doc__.split('Usage:')[1])


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
