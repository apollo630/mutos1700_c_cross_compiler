#!/usr/bin/env python3
"""maketables.py - the real MUTOS 1700 make's tables, for the port.

The port of make (src/mutos_make/) needs two kinds of data that are the
binary's, not v7's source: the parser's yacc tables (yyparse() is yacc's
parser skeleton run on them, gram.y's rules are not compiled again) and
builtin[], the text of the built-in rules and macros that make reads as a
makefile before any other (v7's files.c). This script reads them out of the
binary - data addresses in tests/realbin/makemap.txt - and writes them as C:
makedata.c. Nothing in it is typed by hand. The binary is stripped.

The binary is a 0411 file (separate instruction and data space): the data
begins at address 0.

Usage:
    maketables.py --c                 print makedata.c
    maketables.py --check-c FILE      check FILE is what --c prints
    maketables.py --table             print the tables as the binary has them
"""
import base64
import os
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..', '..'))
BIN = os.path.join(ROOT, 'mutos', 'mutos_bin', 'make.golden.base64.txt')

# yacc's tables, data addresses: name -> (address, number of 16-bit words)
YACC = [
    ('yyexca', 0x982, 6),
    ('yyact', 0x98e, 18),
    ('yypact', 0x9b2, 19),
    ('yypgo', 0x9d8, 9),
    ('yyr1', 0x9ea, 19),
    ('yyr2', 0xa10, 19),
    ('yychk', 0xa36, 19),
    ('yydef', 0xa5c, 19),
]
# YYLAST (the number of words of yyact), YYFLAG, YYERRCODE and YYMAXDEPTH are
# constants of the code of yyparse() - cmp si, 0x12 / 0xfc18 / 0x100 and the
# frame - see gram.c, not tables.

BUILTIN = 0x3b2         # char *builtin[]: pointers, data address, 0 at the end
LINESPTR = 0x54          # char **linesptr = builtin;


def image():
    img = base64.b64decode(open(BIN, 'rb').read())
    magic, tsize, dsize, bsize = struct.unpack_from('<4H', img, 0)
    assert magic == 0o411, oct(magic)
    return img[16 + tsize:16 + tsize + dsize]


def words(data, addr, n):
    return [struct.unpack_from('<h', data, addr + 2 * i)[0] for i in range(n)]


def builtin_lines(data):
    lines = []
    a = BUILTIN
    while True:
        p = struct.unpack_from('<H', data, a)[0]
        a += 2
        if p == 0:
            break
        e = data.index(b'\0', p)
        lines.append(data[p:e].decode('ascii'))
    assert struct.unpack_from('<H', data, LINESPTR)[0] == BUILTIN
    return lines


def cstr(s):
    out = []
    for ch in s:
        if ch == '\\':
            out.append('\\\\')
        elif ch == '"':
            out.append('\\"')
        elif ch == '\t':
            out.append('\\t')
        elif ch == '\n':
            out.append('\\n')
        elif ' ' <= ch <= '~':
            out.append(ch)
        else:
            out.append('\\%03o' % ord(ch))
    return '"' + ''.join(out) + '"'


def c_source():
    data = image()
    lines = builtin_lines(data)
    out = ['/*',
           ' * makedata.c - the tables of the original MUTOS 1700 make',
           ' * (mutos/mutos_bin/make.golden.base64.txt): the eight tables of',
           ' * yacc\'s parser for gram.y, and builtin[], the %d lines of the'
           % len(lines),
           ' * built-in rules and macros. Generated by',
           ' * tests/realbin/maketables.py --c - do not edit; "make',
           ' * check-realbin" checks it is current.',
           ' */',
           '',
           '#include "make.h"',
           '']
    for name, addr, n in YACC:
        out.append('const int16_t make_%s[%d] = {' % (name, n))
        ws = words(data, addr, n)
        for i in range(0, n, 8):
            out.append('\t' + ', '.join('%d' % w for w in ws[i:i + 8]) + ',')
        out.append('};')
        out.append('')
    out.append('const char *const make_builtin[%d] = {' % (len(lines) + 1))
    for i, t in enumerate(lines):
        out.append('\t%s,\t/* %d */' % (cstr(t), i))
    out.append('\tNULL')
    out.append('};')
    out.append('')
    return '\n'.join(out)


def main(argv):
    if argv[:1] == ['--c']:
        sys.stdout.write(c_source())
        return 0
    if len(argv) == 2 and argv[0] == '--check-c':
        if open(argv[1]).read() != c_source():
            print('%s is not what maketables.py --c prints' % argv[1])
            return 1
        print('%s is current' % argv[1])
        return 0
    if argv[:1] == ['--table']:
        data = image()
        for name, addr, n in YACC:
            print('%-7s %04x %s' % (name, addr, words(data, addr, n)))
        for i, t in enumerate(builtin_lines(data)):
            print('%2d %s' % (i, cstr(t)))
        return 0
    sys.exit(__doc__.split('Usage:')[1])


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
